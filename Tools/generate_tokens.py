#!/usr/bin/env python3
"""Generate Swift design tokens and copy keys from the Figma exports.

Inputs:
  Design/figma-variables.json   variables, text styles, effect styles (exported from Figma)
  SlekPDF/Resources/Copy/copy.json   Copy/* strings, {key: {km, en}}
Outputs (overwritten):
  SlekPDF/DesignSystem/Generated/*.swift

Run from the project root:  python3 Tools/generate_tokens.py
"""
import json
import keyword
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "SlekPDF/DesignSystem/Generated"
HEADER = "// Generated by Tools/generate_tokens.py from the Figma exports. Do not edit by hand.\n"
SWIFT_KEYWORDS = {"default", "case", "class", "struct", "enum", "func", "var", "let", "in", "is", "as", "self", "Type", "none"}


def ident(name: str) -> str:
    words = [w for w in re.split(r"[^0-9A-Za-z]+", name) if w]
    if not words:
        raise ValueError(f"cannot make identifier from {name!r}")
    out = words[0][0].lower() + words[0][1:] if not words[0].isupper() or len(words[0]) == 1 else words[0].lower()
    for w in words[1:]:
        out += w if w.isupper() else w[0].upper() + w[1:]
    if out[0].isdigit():
        out = "s" + out
    if out in SWIFT_KEYWORDS or keyword.iskeyword(out):
        out = f"`{out}`"
    return out


def parse_collections(data):
    cols = {}
    for c in data["collections"]:
        vars_ = {}
        for line in c["vars"]:
            parts = [p.strip() for p in line.split(" | ")]
            name, kind, values = parts[0], parts[1], parts[2:]
            vars_[name] = {"kind": kind, "values": dict(zip(c["modes"], values))}
        cols[c["name"]] = {"modes": c["modes"], "vars": vars_}
    return cols


def build_lookup(cols):
    lookup = {}
    for cname, c in cols.items():
        for vname, v in c["vars"].items():
            if vname in lookup:
                sys.exit(f"duplicate variable name across collections: {vname}")
            lookup[vname] = (cname, v)
    return lookup


def resolve(lookup, cols, value, mode):
    """Resolve an alias chain to a literal for the given mode name (Light/Dark/Khmer/English)."""
    seen = set()
    while isinstance(value, str) and value.startswith("→"):
        target = value[1:]
        if target in seen:
            sys.exit(f"alias cycle at {target}")
        seen.add(target)
        cname, v = lookup[target]
        modes = cols[cname]["modes"]
        value = v["values"][mode] if mode in modes else v["values"][modes[0]]
    return value


def rgba(hexstr):
    h = hexstr.lstrip("#")
    if len(h) == 6:
        h += "ff"
    return f"0x{h.upper()}"


def gen_colors(cols, lookup):
    lines = [HEADER, "import AppKit", "import SwiftUI", "",
             "/// Primitive ramps (Figma collection \"Color Promitives\"). Prefer semantic `DSColor` in views.",
             "enum DSPrimitive {"]
    for name, v in cols["Color Promitives"]["vars"].items():
        lines.append(f"    static let {ident(name)} = Color(nsColor: NSColor(rgba: {rgba(v['values']['Mode 1'])}))")
    lines += ["}", "", "/// Semantic colours as AppKit colours (for PDFView and other AppKit views). Resolve with the appearance.", "enum DSNSColor {"]
    for name, v in cols["Color"]["vars"].items():
        light = resolve(lookup, cols, v["values"]["Light"], "Light")
        dark = resolve(lookup, cols, v["values"]["Dark"], "Dark")
        lines.append(f"    /// {name} — Light {v['values']['Light']} ({light}) · Dark {v['values']['Dark']} ({dark})")
        lines.append(f"    static let {ident(name)} = NSColor(name: \"{name}\", light: {rgba(light)}, dark: {rgba(dark)})")
    lines += ["}", "", "/// Semantic colours (Figma collection \"Color\", modes Light/Dark). Resolve with the app appearance.", "enum DSColor {"]
    for name in cols["Color"]["vars"]:
        lines.append(f"    static let {ident(name)} = Color(nsColor: DSNSColor.{ident(name)})")
    lines += ["}", "",
              "/// Colours that depend on the interface language (Figma collection \"Typography\", modes Khmer/English).",
              "enum DSLanguageColor {"]
    for name, v in cols["Typography"]["vars"].items():
        if v["kind"] != "C":
            continue
        cases = []
        for mode, lang in (("Khmer", "km"), ("English", "en")):
            raw = v["values"][mode]
            if raw.startswith("→") and raw[1:] in cols["Color"]["vars"]:
                cases.append(f"case .{lang}: return DSColor.{ident(raw[1:])}")
            else:
                lit = resolve(lookup, cols, raw, mode)
                cases.append(f"case .{lang}: return Color(nsColor: NSColor(rgba: {rgba(lit)}))")
        lines.append(f"    /// {name}")
        lines.append(f"    static func {ident(name)}(_ language: AppLanguage) -> Color {{")
        lines.append("        switch language {")
        lines += [f"        {c}" for c in cases]
        lines += ["        }", "    }"]
    lines.append("}")
    return "\n".join(lines) + "\n"


def gen_spacing(cols):
    groups = {}
    for name, v in cols["Spacing"]["vars"].items():
        group, leaf = name.split("/", 1)
        groups.setdefault(group, []).append((leaf, v["values"]["Value"]))
    lines = [HEADER, "import CoreGraphics", ""]
    for group, items in groups.items():
        lines.append(f"/// Figma Spacing collection — {group}/*")
        lines.append(f"enum DS{group} {{")
        for leaf, val in items:
            lines.append(f"    static let {ident(leaf)}: CGFloat = {val}")
        lines += ["}", ""]
    return "\n".join(lines)


def gen_typography(data, cols):
    tvars = cols["Typography"]["vars"]
    def val(name, mode):
        return tvars[name]["values"][mode]
    lines = [HEADER, "import CoreGraphics", "",
             "/// App text styles (Figma text styles bound to the Typography collection). Web/* styles are website-only.",
             "enum DSTextStyle: CaseIterable {"]
    styles = data["textStyles"]
    for s in styles:
        lines.append(f"    case {ident(s['name'])}")
    lines += ["", "    func spec(for language: AppLanguage) -> DSTextSpec {", "        switch (self, language) {"]
    for s in styles:
        for mode, lang in (("Khmer", "km"), ("English", "en")):
            family = val("Font/Family", mode).replace(" ", "")
            weight = val(f"Font/Weight/{s['weight']}", mode).replace(" ", "")
            size = val(s["size"], mode)
            lh = val(s["lineHeight"], mode)
            lines.append(f"        case (.{ident(s['name'])}, .{lang}): return DSTextSpec(postScriptName: \"{family}-{weight}\", size: {size}, lineHeight: {lh})")
    lines += ["        }", "    }", "}", ""]
    return "\n".join(lines)


def gen_elevation(data):
    lines = [HEADER, "import SwiftUI", "", "/// Figma effect styles Elevation/0–4.", "enum DSElevation: CaseIterable {"]
    names = []
    for e in data["effectStyles"]:
        names.append((ident(e["name"].split("/", 1)[1].lstrip("0123456789 ")), e))
        lines.append(f"    case {names[-1][0]}")
    lines += ["", "    var shadows: [DSShadow] {", "        switch self {"]
    for nm, e in names:
        shadows = [f"DSShadow(color: Color(nsColor: NSColor(rgba: {rgba(x['c'])})), x: {x['x']}, y: {x['y']}, radius: {x['r']})"
                   for x in e["effects"] if x["t"] == "DROP_SHADOW"]
        lines.append(f"        case .{nm}: return [{', '.join(shadows)}]")
    lines += ["        }", "    }", "", "    /// Background blur radius, if the style has one.", "    var backgroundBlur: CGFloat? {", "        switch self {"]
    for nm, e in names:
        blur = next((x["r"] for x in e["effects"] if x["t"] == "BACKGROUND_BLUR"), None)
        lines.append(f"        case .{nm}: return {blur if blur is not None else 'nil'}")
    lines += ["        }", "    }", "}"]
    return "\n".join(lines) + "\n"


def gen_copy_keys(copy):
    lines = [HEADER, "/// Keys of `copy.json`; raw values are the Figma `Copy/<name>` variable names.", "enum CopyKey: String, CaseIterable {"]
    used = set()
    for key in copy:
        name = ident(key)
        base, n = name, 2
        while name in used:
            name, n = f"{base}{n}", n + 1
        used.add(name)
        lines.append(f"    case {name} = \"{key}\"")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main():
    data = json.loads((ROOT / "Design/figma-variables.json").read_text())
    copy = json.loads((ROOT / "SlekPDF/Resources/Copy/copy.json").read_text())
    for key, v in copy.items():
        if not v.get("km") or not v.get("en"):
            sys.exit(f"copy key {key!r} is missing a Khmer or English value")
        if re.search(r"[ក-៿]", v["en"]):
            sys.exit(f"copy key {key!r} has Khmer glyphs in its English value")
    cols = parse_collections(data)
    lookup = build_lookup(cols)
    OUT.mkdir(parents=True, exist_ok=True)
    files = {
        "DSColors.swift": gen_colors(cols, lookup),
        "DSSpacing.swift": gen_spacing(cols),
        "DSTypography.swift": gen_typography(data, cols),
        "DSElevation.swift": gen_elevation(data),
        "CopyKey.swift": gen_copy_keys(copy),
    }
    for name, text in files.items():
        (OUT / name).write_text(text)
    print(f"wrote {len(files)} files to {OUT.relative_to(ROOT)} ({len(copy)} copy keys)")


if __name__ == "__main__":
    main()
