#!/usr/bin/env python3
"""Turn the Figma icon exports in Design/icons/*.svg into the app's asset catalog.

Figma's MCP export renders each icon in its page context, so every SVG carries two background
rects (the dark canvas and the white "Source components" frame). They are removed here.

- IconPark icons become template images (tinted with the current text colour in SwiftUI).
- Brand/* and File Type/* icons keep their original colours.
- Design/appicon/AppIcon-1024.png becomes the macOS AppIcon set.

Run from the project root:  python3 Tools/import_icons.py
"""
import json
import re
import shutil
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "Design/icons"
CATALOG = ROOT / "SlekPDF/Resources/Assets.xcassets"
ICONS = CATALOG / "Icons"
ORIGINAL_COLOUR = {"brand-microsoft-word", "brand-microsoft-excel", "file-type-pdf"}

CANVAS_RECTS = [
    re.compile(r'<rect width="24" height="24" fill="#1E1E1E"/>\n?'),
    re.compile(r'<rect width="1040" height="1266" transform="translate\([^)]*\)" fill="white"/>\n?'),
]


def write_json(path: Path, data: dict) -> None:
    path.write_text(json.dumps(data, indent=2) + "\n")


def clean(svg: str, name: str) -> str:
    for pattern in CANVAS_RECTS:
        svg, count = pattern.subn("", svg, count=1)
        if count != 1:
            raise SystemExit(f"{name}: expected Figma canvas rect not found; check the export")
    return svg


def write_icon_enum(names: list[str]) -> None:
    lines = ["// Generated by Tools/import_icons.py from the Figma Iconography page (30:1316). Do not edit by hand.", "",
             "/// Every icon in the Figma Iconography page; raw values are asset names under Assets.xcassets/Icons.",
             "enum DSIcon: String, CaseIterable {"]
    for name in names:
        words = name.split("-")
        ident = words[0] + "".join(w[:1].upper() + w[1:] for w in words[1:])
        lines.append(f'    case {ident} = "{name}"')
    lines.append("}")
    (ROOT / "SlekPDF/DesignSystem/Generated/DSIcon.swift").write_text("\n".join(lines) + "\n")


def main() -> None:
    if ICONS.exists():
        shutil.rmtree(ICONS)
    ICONS.mkdir(parents=True)
    write_json(CATALOG / "Contents.json", {"info": {"author": "xcode", "version": 1}})
    write_json(ICONS / "Contents.json", {"info": {"author": "xcode", "version": 1}, "properties": {"provides-namespace": True}})

    svgs = sorted(SRC.glob("*.svg"))
    for svg_path in svgs:
        name = svg_path.stem
        imageset = ICONS / f"{name}.imageset"
        imageset.mkdir()
        (imageset / f"{name}.svg").write_text(clean(svg_path.read_text(), name))
        write_json(imageset / "Contents.json", {
            "images": [{"filename": f"{name}.svg", "idiom": "universal"}],
            "info": {"author": "xcode", "version": 1},
            "properties": {
                "preserves-vector-representation": True,
                "template-rendering-intent": "original" if name in ORIGINAL_COLOUR else "template",
            },
        })

    appicon = CATALOG / "AppIcon.appiconset"
    if appicon.exists():
        shutil.rmtree(appicon)
    appicon.mkdir()
    master = ROOT / "Design/appicon/AppIcon-1024.png"
    images = []
    for points in (16, 32, 128, 256, 512):
        for scale in (1, 2):
            pixels = points * scale
            filename = f"icon_{points}x{points}@{scale}x.png"
            subprocess.run(["sips", "-z", str(pixels), str(pixels), str(master), "--out", str(appicon / filename)],
                           check=True, capture_output=True)
            images.append({"filename": filename, "idiom": "mac", "scale": f"{scale}x", "size": f"{points}x{points}"})
    write_json(appicon / "Contents.json", {"images": images, "info": {"author": "xcode", "version": 1}})
    write_icon_enum([p.stem for p in svgs])
    print(f"{len(svgs)} icons, AppIcon with {len(images)} sizes -> {CATALOG.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
